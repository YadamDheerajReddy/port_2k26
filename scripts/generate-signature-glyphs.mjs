// One-off generator: extracts real per-letter SVG path data for "Dheeraj"
// from the actual Rock Salt font file, for the About section's signature
// watermark stroke-draw animation. Mirrors generate-name-glyphs.mjs exactly.
// Run with: node scripts/generate-signature-glyphs.mjs
// Output is committed as lib/signature-glyphs.ts, this script does not run
// at build time or ship to the browser. The source font lives in
// scripts/assets/, not public/fonts/, since (unlike the Fontshare display
// fonts) Rock Salt is never rendered live on the page, only used once here
// to extract path data -- keeping it out of public/ keeps it out of the
// deployed bundle too.

import { openSync } from "fontkit";
import { writeFileSync } from "fs";
import { fileURLToPath } from "url";
import { dirname, join } from "path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const fontPath = join(__dirname, "assets/RockSalt-Regular.ttf");
const outPath = join(__dirname, "../lib/signature-glyphs.ts");

const text = "Dheeraj";
const font = openSync(fontPath);
const run = font.layout(text);

let cursorX = 0;
const letters = [];
let minY = Infinity;
let maxY = -Infinity;

run.glyphs.forEach((glyph, i) => {
  const position = run.positions[i];
  const path = glyph.path.toSVG();
  const bbox = glyph.path.bbox;

  letters.push({
    char: text[i],
    d: path,
    x: cursorX + position.xOffset,
  });

  if (bbox.minY < minY) minY = bbox.minY;
  if (bbox.maxY > maxY) maxY = bbox.maxY;

  cursorX += position.xAdvance;
});

const totalWidth = cursorX;
const unitsPerEm = font.unitsPerEm;

const output = `/**
 * Auto-generated by scripts/generate-signature-glyphs.mjs from the real
 * RockSalt-Regular.ttf file. Do not hand-edit; regenerate instead.
 * Coordinates are in font units, y-up (baseline at 0). SignatureWatermark.tsx
 * flips the y-axis and positions the viewBox.
 */

export type SignatureGlyph = {
  char: string;
  d: string;
  x: number;
};

export const signatureGlyphs: SignatureGlyph[] = ${JSON.stringify(letters, null, 2)};

export const signatureGlyphsMeta = {
  totalWidth: ${totalWidth},
  unitsPerEm: ${unitsPerEm},
  minY: ${minY},
  maxY: ${maxY},
};
`;

writeFileSync(outPath, output);
console.log(`Wrote ${letters.length} glyphs to ${outPath}`);
console.log(
  `totalWidth=${totalWidth} unitsPerEm=${unitsPerEm} minY=${minY} maxY=${maxY}`,
);
